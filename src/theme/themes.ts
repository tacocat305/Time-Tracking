export const defaultThemeName: ThemeName = "summer";

export const defaultColorMode: ColorMode = "light";

export function getThemeGroupForTheme(themeName: ThemeName): ThemeGroupId {
  return themeDefinitions[themeName].groupId;
}

export function getThemePreviewSwatches(
  themeName: ThemeName,
  colorMode: ColorMode = defaultColorMode
) {
  const activePalette = themeDefinitions[themeName][colorMode];

  return [
    activePalette.background,
    activePalette.accent,
    activePalette.panelRaised,
  ];
}

export function buildThemeStyle(
  themeName: ThemeName,
  colorMode: ColorMode
): CSSProperties {
  const activePalette = themeDefinitions[themeName][colorMode];

  return {
    colorScheme: colorMode,
    "--color-accent": activePalette.accent,
    "--color-accent-soft": activePalette.accentSoft,
    "--color-accent-strong": activePalette.accentStrong,
    "--color-background": activePalette.background,
    "--color-border": activePalette.border,
    "--color-danger": activePalette.danger,
    "--color-muted": activePalette.muted,
    "--color-nav-background": activePalette.navBackground,
    "--color-panel": activePalette.panel,
    "--color-panel-raised": activePalette.panelRaised,
    "--color-success": activePalette.success,
    "--color-text": activePalette.text,
    "--color-warning": activePalette.warning,
  } as CSSProperties;
}
