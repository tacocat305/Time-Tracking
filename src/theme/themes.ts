import type { CSSProperties } from "react";

export type ColorMode = "light" | "dark";

export type ThemeGroupId = "f1" | "cities" | "traditional" | "seasons";

export interface ThemePalette {
  accent: string;
  accentSoft: string;
  accentStrong: string;
  background: string;
  border: string;
  danger: string;
  muted: string;
  navBackground: string;
  panel: string;
  panelRaised: string;
  success: string;
  text: string;
  warning: string;
}

interface ThemeDefinition {
  category: string;
  description: string;
  groupId: ThemeGroupId;
  label: string;
  light: ThemePalette;
  dark: ThemePalette;
}

type PaletteTuple = [
  accent: string,
  accentSoft: string,
  accentStrong: string,
  background: string,
  border: string,
  danger: string,
  muted: string,
  navBackground: string,
  panel: string,
  panelRaised: string,
  success: string,
  text: string,
  warning: string,
];

function palette([
  accent,
  accentSoft,
  accentStrong,
  background,
  border,
  danger,
  muted,
  navBackground,
  panel,
  panelRaised,
  success,
  text,
  warning,
]: PaletteTuple): ThemePalette {
  return {
    accent,
    accentSoft,
    accentStrong,
    background,
    border,
    danger,
    muted,
    navBackground,
    panel,
    panelRaised,
    success,
    text,
    warning,
  };
}

function theme(definition: {
  category: string;
  description: string;
  groupId: ThemeGroupId;
  label: string;
  light: PaletteTuple;
  dark: PaletteTuple;
}): ThemeDefinition {
  return {
    ...definition,
    light: palette(definition.light),
    dark: palette(definition.dark),
  };
}

